"""
Regression tests: the packaged code must reproduce the outputs of the original
(unpackaged) group code. `data/reference-outputs.npz` was generated by running the
same simulations with the original `util.py` / `lumped/` / `cellparams/` / `pybammeis/`
scripts (OneDrive drop, 2026-09-23) against pybamm 25.1.1.

Tests run from the repo root, where no XLSX_CELLDEFS/ folder exists, so they also
check that nothing depends on the working directory.
"""
from pathlib import Path

import numpy as np
import pybamm
import pytest

import lumped

DATA = Path(__file__).parent / "data"
REF = np.load(DATA / "reference-outputs.npz")
RTOL = 1e-6


@pytest.fixture(scope="module")
def cell():
    return lumped.load_cell_params(DATA / "cellNMC30.xlsx")


def test_sim_cc(cell):
    Q = cell.const.Q()
    sim = lumped.sim_cc(cell, 1 * Q, 100, 80, t_rest=10 * 60)
    np.testing.assert_allclose(sim.solution["time [s]"].entries, REF["cc_t"], rtol=RTOL)
    np.testing.assert_allclose(sim.solution["vcell [V]"].entries, REF["cc_v"], rtol=RTOL)


def test_sim_gitt(cell):
    Q = cell.const.Q()
    sim = lumped.sim_gitt(cell, 300, 600, 0.5 * Q, 60, 50)
    np.testing.assert_allclose(sim.solution["vcell [V]"].entries, REF["gitt_v"], rtol=RTOL)


def test_sim_eis(cell):
    freq = np.logspace(-2, 3, 11)
    eis = lumped.sim_eis(cell, freq, 50)
    np.testing.assert_allclose(np.array(eis.solution), REF["eis_Z"], rtol=RTOL)


def test_lib_default_parameter_values():
    sim = pybamm.Simulation(lumped.LumpedLIBModel())
    sim.solve([0, 600])
    np.testing.assert_allclose(sim.solution["vcell [V]"].entries, REF["lib_default_v"], rtol=RTOL)


def test_lmb_default_parameter_values():
    sim = pybamm.Simulation(lumped.LumpedLMBModel(J=2))
    sim.solve([0, 600])
    np.testing.assert_allclose(sim.solution["vcell [V]"].entries, REF["lmb_default_v"], rtol=RTOL)
